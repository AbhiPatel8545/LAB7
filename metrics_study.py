"""Piece 5: Metrics study with Frechet distance, precision, recall, and nearest-train distance.

This script compares the quality of samples generated by:
1. Autoencoder (decoded from prior samples)
2. VAE (beta=1)
3. VAE with different KL weights (beta sweep)

For each model, it reports:
- Frechet distance (lower is better, measures distribution quality)
- Precision (higher is better, measures how close samples are to real data manifold)
- Recall (higher is better, measures coverage of real data)
- Nearest-train distance (lower is better, measures memorization)

Run: python metrics_study.py
"""
import numpy as np
import torch

import lab07_starter as S
from vae import VAE, train_vae

torch.manual_seed(0)
np.random.seed(0)

print("=" * 70)
print("Piece 5: Metrics Study")
print("=" * 70)

Xtr, ytr, Xte, yte = S.load_task()
print(f"train {tuple(Xtr.shape)}, test {tuple(Xte.shape)}")

# ---------------------------------------------------------------- train all models
print("\n--- Training models ---")

epochs = 50  # Reduced for faster execution
lr = 2e-3
batch_size = 64
seed = 0
n_samples = 359  # number of prior samples to score

# Train feature network (shared for all evaluations)
print("Training feature network...")
net = S.train_feature_net(Xtr, ytr, epochs=40, seed=0)
fte = S.get_features(net, Xte)

# Train autoencoder
print("Training autoencoder...")
ae = S.AE(d_latent=8, d_hidden=64)
S.train(ae, S.ae_loss, Xtr, epochs=epochs, lr=lr, batch_size=batch_size, seed=seed)

# Train VAE with beta=1
print("Training VAE (beta=1)...")
vae = VAE(d_latent=8, d_hidden=64)
train_vae(vae, Xtr, epochs=epochs, lr=lr, batch_size=batch_size, seed=seed, beta=1.0)

# Train additional VAEs for beta sweep
betas = [0.1, 0.5, 1.0, 2.0, 4.0]
vae_models = {}
for beta in betas:
    print(f"Training VAE (beta={beta})...")
    vae_models[beta] = VAE(d_latent=8, d_hidden=64)
    train_vae(vae_models[beta], Xtr, epochs=epochs, lr=lr, batch_size=batch_size, seed=seed, beta=beta)

# ---------------------------------------------------------------- generate samples
print("\n--- Generating samples ---")

g = torch.Generator().manual_seed(seed)

# Generate samples from each model
ae_samples = ae.decode(torch.randn(n_samples, 8, generator=g)).clamp(0, 1)

vae_samples = vae.decode(torch.randn(n_samples, 8, generator=g)).clamp(0, 1)

# Save sample grids
S.save_grid(ae_samples[:32], "figures/metrics_ae_samples.png", ncols=16,
            title="AE samples from N(0,I), decoded")
S.save_grid(vae_samples[:32], "figures/metrics_vae_samples.png", ncols=16,
            title="VAE samples from N(0,I), decoded")

# Save all samples for comparison
all_ae = ae_samples.clone()
all_vae = vae_samples.clone()
for beta in betas:
    if beta != 1.0:  # VAE with beta=1 already generated
        vae_samp = vae_models[beta].decode(torch.randn(n_samples, 8, generator=g)).clamp(0, 1)
        all_vae = torch.cat([all_vae, vae_samp], dim=0)
        S.save_grid(vae_samp[:32], f"figures/metrics_vae_beta{beta}_samples.png", ncols=16,
                    title=f"VAE samples (beta={beta}) from N(0,I), decoded")

# Also generate combined comparison
S.save_grid(all_vae[:64], "figures/metrics_all_vae_samples.png", ncols=16,
            title="VAE samples at different beta values (beta=0.1,0.5,1,2,4 from top)")

# ---------------------------------------------------------------- compute metrics
print("\n--- Computing metrics ---")

# Score all samples
results = {}

# AE samples
ae_metrics = S.score_samples(ae_samples, fte, net, Xtr)
results['AE'] = ae_metrics
print(f"AE:    Frechet={ae_metrics['frechet']:.1f}, Precision={ae_metrics['precision']:.3f}, "
      f"Recall={ae_metrics['recall']:.3f}, NearestTrain={ae_metrics['nearest_train']:.2f}")

# VAE beta=1
vae_metrics = S.score_samples(vae_samples, fte, net, Xtr)
results['VAE (beta=1)'] = vae_metrics
print(f"VAE1:  Frechet={vae_metrics['frechet']:.1f}, Precision={vae_metrics['precision']:.3f}, "
      f"Recall={vae_metrics['recall']:.3f}, NearestTrain={vae_metrics['nearest_train']:.2f}")

# VAE for each beta
for beta in betas:
    if beta != 1.0:
        vae_samp = vae_models[beta].decode(torch.randn(n_samples, 8, generator=g)).clamp(0, 1)
        vae_b_metrics = S.score_samples(vae_samp, fte, net, Xtr)
        results[f'VAE (beta={beta})'] = vae_b_metrics
        print(f"VAE b={beta}: Frechet={vae_b_metrics['frechet']:.1f}, Precision={vae_b_metrics['precision']:.3f}, "
              f"Recall={vae_b_metrics['recall']:.3f}, NearestTrain={vae_b_metrics['nearest_train']:.2f}")

# ---------------------------------------------------------------- create metrics comparison table
print("\n" + "=" * 70)
print("Metrics Comparison Table")
print("=" * 70)

print("\n| Model         | Frechet | Precision | Recall | Nearest-Train |")
print("|---------------|---------|-----------|--------|---------------|")
print(f"| AE            | {ae_metrics['frechet']:7.1f} | {ae_metrics['precision']:9.3f} | {ae_metrics['recall']:6.3f} | {ae_metrics['nearest_train']:13.2f} |")
print(f"| VAE (beta=1)  | {vae_metrics['frechet']:7.1f} | {vae_metrics['precision']:9.3f} | {vae_metrics['recall']:6.3f} | {vae_metrics['nearest_train']:13.2f} |")

for beta in betas:
    if beta != 1.0:
        vae_samp = vae_models[beta].decode(torch.randn(n_samples, 8, generator=g)).clamp(0, 1)
        vae_b_metrics = S.score_samples(vae_samp, fte, net, Xtr)
        print(f"| VAE (b={beta})  | {vae_b_metrics['frechet']:7.1f} | {vae_b_metrics['precision']:9.3f} | {vae_b_metrics['recall']:6.3f} | {vae_b_metrics['nearest_train']:13.2f} |")

# ---------------------------------------------------------------- analysis
print("\n" + "=" * 70)
print("Analysis")
print("=" * 70)
print("""
METRICS INTERPRETATION:

1. Frechet Distance: Measures the distance between the feature distribution of
   real data and generated samples. Lower is better. The VAE typically has lower
   Frechet distance than the AE because its samples are more diverse and closer
   to the data manifold.

2. Precision: Share of generated samples that are "close" to real data
   (within k-NN radius of the feature space). Higher precision means fewer
   outliers. The VAE tends to have higher precision because the KL term
   regularizes it to stay on the data manifold.

3. Recall: Share of real data points that are "close" to generated samples.
   Higher recall means the generator covers more of the data distribution.
   The AE may have higher recall because it learns to reconstruct training
   data well, but its samples may not cover the full data manifold.

4. Nearest-Train Distance: Average pixel distance from generated samples to
   nearest training image. Lower values indicate memorization. An AE trained
   with reconstruction loss may have low values (copying training data), while
   a VAE typically has higher values (generating new samples).

KEY OBSERVATIONS:
- Autoencoder samples often look sharper but may not generalize well.
- VAE samples are more diverse but may be blurrier.
- Beta controls the trade-off: lower beta = better reconstruction, higher beta = better prior matching.
- Very high beta (4.0) can cause posterior collapse - the model ignores the latent code.
""")